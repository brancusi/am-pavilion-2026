// The home page's share of the press set: the works gallery ("The units,
// assembled") and On the bench. Run by press.mjs after every press list, or
// on its own from resources/data/press/press.json:
//
//   node scripts/press-home.mjs
//
// An image goes where its `home` field in Caption Genius says (works, bench,
// none); left blank, the installation views, renderings and process shots go
// in the gallery and the rest stay out. Each gets the gallery's two lines
// (the work, then what the picture is and its year) and its alt text: the
// `alt` field, else one made from the caption.
//
// Also writes the English of every image text for translation
// (resources/i18n/en/data-media.json, scripts/press-i18n.mjs).
//
// Writes resources/data/press/home.json, which the home page fetches (so a
// Sync shows at once), and src/amp/data/press_home.cljs, the same list built
// into the page so it lays out before the fetch. Don't edit either by hand.

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { writeMediaCatalog } from './press-i18n.mjs';

const JSON_OUT = 'resources/data/press/home.json';
const CLJS_OUT = 'src/amp/data/press_home.cljs';
const BY_SECTION = { pavilion: 'works', renderings: 'works', process: 'works' };
// The gallery runs installed works, then (after the slides kept in code)
// drawings and renderings, then the studio.
const SECTIONS = ['pavilion', 'renderings', 'process'];

const cap = (s) => s.charAt(0).toUpperCase() + s.slice(1);
const year = (i) => (i.caption.match(/\b(20\d\d)\.(?:\s|$)/) || [, i.date || '2026'])[1];
const sentences = (c) => c.split(/(?<=\.)\s+(?=[A-Z])/).map((s) => s.trim().replace(/\.$/, ''));

// The work, and what the picture is ("Rendering, Yerevan", "Installation view").
function lines(i) {
  if (i.section === 'renderings') {
    const at = i.title.lastIndexOf(', ');
    const kind = at < 0 ? 'rendering' : i.title.slice(at + 2);
    return [at < 0 ? i.title : i.title.slice(0, at),
      cap(kind.replace('rendering in the Pavilion', 'rendering, Tesa 41').replace(/rendering in /, 'rendering, '))];
  }
  if (i.section === 'pavilion') {
    const kind = /Installation view/.test(i.caption) ? 'Installation view'
      : /Los Angeles/.test(i.caption) ? 'Los Angeles' : 'The Studio';
    return [i.title.replace(/, installation view$/, ''), kind];
  }
  return [i.title, 'In the studio'];
}

function alt(i, work) {
  if (i.alt) return i.alt;
  const c = i.caption;
  if (c.includes(': ')) {   // "Work in progress for The Studio…: what it shows, Tesa 41, 2026. Photo: …"
    const a = c.slice(c.indexOf(': ') + 2).replace(/(, Tesa 41)?(, 20\d\d)?\.\s*Photo:.*$/, '').replace(/\.$/, '');
    return cap(a) + '.';
  }
  const keep = sentences(c).filter((s) => !/^(Photo|Rendering:|Courtesy|Zadik Zadikian,|Pigmented|Plaster,|Not in)/.test(s));
  return [work, ...keep].filter(Boolean).join('. ') + '.';
}

export function homeList(images) {
  const out = [];
  for (const i of images) {
    const home = i.home || BY_SECTION[i.section] || 'none';
    if (home === 'none') continue;
    const [work, kind] = lines(i);
    out.push({
      uid: i.uid, w: i.w, h: i.h, section: i.section, home,
      title: work, line: `${kind} · ${year(i)}`, alt: alt(i, work),
      ...(i.credit && i.credit !== 'Aram Zadikian' ? { photo: i.credit } : {}),
    });
  }
  // The gallery by section, each in the project's order; the bench as it is.
  const rank = (e) => (e.home === 'bench' ? -1 : SECTIONS.indexOf(e.section));
  return out.map((e, n) => [e, n]).sort((a, b) => rank(a[0]) - rank(b[0]) || a[1] - b[1]).map(([e]) => e);
}

const edn = (v) => typeof v === 'string' ? JSON.stringify(v)
  : typeof v === 'number' ? String(v)
  : `{${Object.entries(v).map(([k, x]) => `:${k} ${edn(x)}`).join(' ')}}`;

export function writeHome(images) {
  const list = homeList(images);
  writeFileSync(JSON_OUT, JSON.stringify(list, null, 1) + '\n');
  writeFileSync(CLJS_OUT, `(ns amp.data.press-home
  "Generated by scripts/press-home.mjs from the press list; don't edit. The
   home page's images from the press set as they were at the last build:
   the works gallery's (:home \\"works\\") and On the bench's (\\"bench\\"). The
   page lays out from this, then takes the live /data/press/home.json.")

(def images
  [${list.map(edn).join('\n   ')}])
`);
  writeMediaCatalog(images, list);
  console.log(`Home: ${list.filter((e) => e.home === 'works').length} in the gallery, ${list.filter((e) => e.home === 'bench').length} on the bench`);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeHome(JSON.parse(readFileSync('resources/data/press/press.json', 'utf8')).images);
}
